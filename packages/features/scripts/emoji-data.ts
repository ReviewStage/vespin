// emoji-data.ts -- writes or checks `src/generated/emoji-data.ts`, every emoji a picker offers, trimmed from emojibase's English data.

import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { argv, exit } from "node:process";
import { fileURLToPath } from "node:url";
import { Schema } from "effect";
import type { EmojiDataEmoji, EmojiDataGroup } from "../src/emoji-model.js";

/**
 * Note that we write a trimmed copy rather than import emojibase's own
 * `en/data.json`, because over half of that file is skin-tone variants and
 * fields no picker reads, and the iOS app carries whatever it imports in its
 * one bundle. The copy keeps, for each base emoji, its CLDR name, the emoji
 * version it came in (which `emoji-model.ts` caps), its CLDR keywords, and
 * its GitHub shortcodes, the set developers type in a pull request.
 */

/** The written module, beside the model that reads it. */
const OUT = fileURLToPath(new URL("../src/generated/emoji-data.ts", import.meta.url));

/** emojibase's group that holds the skin tones and hair styles an emoji is built from, never offered alone. */
const COMPONENT_GROUP = "component";

/** An emoji as `emojibase-data/en/data.json` lists it, of which only these keys are read; a regional indicator has no group. */
const EmojibaseEmoji = Schema.Struct({
  emoji: Schema.String,
  label: Schema.String,
  hexcode: Schema.String,
  version: Schema.Number,
  order: Schema.optionalKey(Schema.Number),
  group: Schema.optionalKey(Schema.Number),
  tags: Schema.optionalKey(Schema.Array(Schema.String)),
});

/** The files read, each as its JSON is parsed: the package's version, the emoji, their groups' names, and GitHub's shortcodes, one or several to an emoji's hexcode. */
const EMOJIBASE_FILE = {
  PACKAGE: Schema.Struct({ version: Schema.String }),
  DATA: Schema.Array(EmojibaseEmoji),
  MESSAGES: Schema.Struct({
    groups: Schema.Array(
      Schema.Struct({ key: Schema.String, message: Schema.String, order: Schema.Number }),
    ),
  }),
  SHORTCODES: Schema.Record(Schema.String, Schema.ArrayEnsure(Schema.String)),
} as const;

const require = createRequire(import.meta.url);

/** One of emojibase's files, parsed by its schema. */
async function emojibase<S extends Schema.Decoder<unknown>>(
  file: string,
  schema: S,
): Promise<S["Type"]> {
  const text = await readFile(require.resolve(file), "utf8");

  return Schema.decodeUnknownSync(Schema.fromJsonString(schema))(text);
}

/** A group's name as Unicode writes it, each word capitalized: "smileys & emotion" as "Smileys & Emotion". */
function groupName(message: string): string {
  return message.replace(/\b\p{L}/gu, (letter) => letter.toUpperCase());
}

/** Every base emoji by group, in Unicode's order, as a picker reads them. */
async function emojiData(): Promise<{ version: string; groups: EmojiDataGroup[] }> {
  const { version } = await emojibase("emojibase-data/package.json", EMOJIBASE_FILE.PACKAGE);
  const data = await emojibase("emojibase-data/en/data.json", EMOJIBASE_FILE.DATA);
  const messages = await emojibase("emojibase-data/en/messages.json", EMOJIBASE_FILE.MESSAGES);

  const github = await emojibase(
    "emojibase-data/en/shortcodes/github.json",
    EMOJIBASE_FILE.SHORTCODES,
  );

  const ordered = [...data].sort((a, b) => (a.order ?? 0) - (b.order ?? 0));

  const groups = [...messages.groups]
    .sort((a, b) => a.order - b.order)
    .filter((group) => group.key !== COMPONENT_GROUP)
    .map((group) => ({
      name: groupName(group.message),
      emojis: ordered
        .filter((one) => one.group === group.order)
        .map(
          (one): EmojiDataEmoji => ({
            emoji: one.emoji,
            name: one.label,
            version: one.version,
            keywords: one.tags ?? [],
            shortcodes: github[one.hexcode] ?? [],
          }),
        ),
    }));

  return { version, groups };
}

/**
 * The module's text: one emoji to a line, so an upgrade's diff reads as the
 * emoji it added or changed. Note that Biome is kept off the file
 * (`biome.json`), which would spread its two thousand emoji over some
 * seventeen thousand lines.
 */
async function moduleText(): Promise<string> {
  const { version, groups } = await emojiData();

  const group = (one: EmojiDataGroup) =>
    [
      `  {`,
      `    name: ${JSON.stringify(one.name)},`,
      `    emojis: [`,
      ...one.emojis.map((emoji) => `      ${JSON.stringify(emoji)},`),
      `    ],`,
      `  },`,
    ].join("\n");

  return [
    `// Generated by packages/features/scripts/emoji-data.ts from emojibase-data ${version}. Do not edit`,
    "// by hand: run `pnpm --filter @repo/features emoji:data` after upgrading emojibase-data.",
    "",
    'import type { EmojiDataGroup } from "../emoji-model.js";',
    "",
    "/** Every base emoji by Unicode's categories: its CLDR name, emoji version, CLDR keywords, and GitHub shortcodes. */",
    "export const EMOJI_DATA: readonly EmojiDataGroup[] = [",
    ...groups.map(group),
    "];",
    "",
  ].join("\n");
}

const wanted = await moduleText();

if (argv.includes("--check")) {
  const current = await readFile(OUT, "utf8").catch(() => undefined);

  if (current !== wanted) {
    console.error(
      "emoji-data: src/generated/emoji-data.ts is stale; run `pnpm --filter @repo/features emoji:data`",
    );
    exit(1);
  }
} else {
  await writeFile(OUT, wanted);
}
